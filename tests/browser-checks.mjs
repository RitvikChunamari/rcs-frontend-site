import assert from 'node:assert/strict'

// Accepts a standard Playwright Page; no proprietary runner is required.
export async function verifyDemo(page, base = 'http://localhost:5178/rcs-frontend-site/') {
  const passed = []
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${base}comparison/after/index.html`)
  await page.evaluate(() => localStorage.removeItem('threadline-studio-v1'))
  await page.reload()
  const search = page.getByRole('searchbox', { name: 'Search signals' })
  const signals = page.getByRole('list', { name: 'Customer signals' })
  await search.fill('SHARE')
  await page.getByLabel('Filter signals', { exact: true }).selectOption('decided')
  assert.equal(await signals.getByRole('button').count(), 1)
  await search.fill('unfindable')
  assert.equal(await page.getByText('No signals on this thread.').count(), 1)
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  assert.equal(await signals.getByRole('button').count(), 5)
  passed.push('search, combined filter, empty state, reset')

  await page.getByRole('button', { name: 'Add signal', exact: true }).click()
  await page.getByRole('button', { name: 'Save signal', exact: false }).click()
  assert.equal(await page.locator('#signal-title').getAttribute('aria-invalid'), 'true')
  assert.equal(await page.locator('#signal-title').evaluate(el => el === document.activeElement), true)
  await page.getByLabel('Title', { exact: false }).fill('Export the customer context')
  await page.getByRole('textbox', { name: 'Customer context', exact: false }).fill('A decision should travel with its source conversation and useful context.')
  await page.getByRole('button', { name: 'Save signal', exact: false }).click()
  assert.equal(await page.getByRole('dialog').count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Add signal', exact: true }).evaluate(el => el === document.activeElement), true)
  assert.equal(await signals.getByRole('button').count(), 6)
  await page.reload()
  assert.equal(await signals.getByRole('button').count(), 6)
  await page.getByRole('button', { name: 'Add to decision', exact: false }).click()
  assert.equal(await page.getByRole('button', { name: 'Remove from decision', exact: false }).count(), 1)
  passed.push('validation, focus return, create, persistence, decision toggle')

  // A real Storage failure at the persistence boundary; not the error preview.
  await page.getByRole('button', { name: 'Add signal', exact: true }).click()
  await page.getByLabel('Title', { exact: false }).fill('A retained failure draft')
  await page.getByRole('textbox', { name: 'Customer context', exact: false }).fill('This input must remain available when storage fails.')
  await page.evaluate(() => { window.__originalSetItem = Storage.prototype.setItem; Storage.prototype.setItem = function () { throw new DOMException('Quota exceeded', 'QuotaExceededError') } })
  await page.getByRole('button', { name: 'Save signal', exact: false }).click()
  assert.equal(await page.getByRole('dialog').count(), 1)
  assert.match(await page.getByRole('dialog').getByRole('alert').innerText(), /could not save/)
  assert.equal(await page.locator('#signal-title').inputValue(), 'A retained failure draft')
  await page.evaluate(() => { Storage.prototype.setItem = window.__originalSetItem; delete window.__originalSetItem })
  await page.getByRole('button', { name: 'Save signal', exact: false }).click()
  assert.equal(await page.getByRole('dialog').count(), 0)
  passed.push('actual storage failure retains draft; retry succeeds')

  for (const [state, text] of [['loading', 'Gathering the signals.'], ['empty', 'Your next insight starts here.'], ['error', 'The thread was interrupted.']]) {
    await page.getByLabel('Explore interface states').selectOption(state)
    assert.equal(await page.getByRole('heading', { name: text, exact: true }).count(), 1)
  }
  await page.getByRole('button', { name: 'Retry preview', exact: false }).click()
  assert.equal(await signals.getByRole('button').count(), 7)
  passed.push('loading, empty, error previews and recovery')

  await page.getByRole('button', { name: 'Reset demo', exact: true }).click()
  await page.getByRole('button', { name: 'Keep my changes', exact: true }).click()
  assert.equal(await signals.getByRole('button').count(), 7)
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click()
  await page.getByRole('button', { name: 'Reset workspace', exact: true }).click()
  assert.equal(await signals.getByRole('button').count(), 5)
  passed.push('reset cancellation and confirmed reset')

  await page.getByRole('radio', { name: 'Swiss Your direction', exact: false }).check()
  assert.equal(await page.locator('html').getAttribute('data-direction'), 'swiss')
  await page.getByRole('radio', { name: 'Editorial Your direction', exact: false }).check()
  assert.equal(await page.locator('html').getAttribute('data-direction'), 'editorial')
  await page.getByRole('radio', { name: 'Swiss + editorial', exact: false }).check()
  passed.push('all three art-direction presets')

  await page.locator('#motion').scrollIntoViewIfNeeded()
  await page.getByRole('button', { name: 'Replay story', exact: true }).click()
  await page.waitForTimeout(300)
  const progress = page.getByRole('slider', { name: 'Story progress', exact: true })
  assert.ok(Number(await progress.inputValue()) > 0)
  await page.getByRole('button', { name: 'Pause story', exact: true }).click()
  const paused = Number(await progress.inputValue())
  await page.waitForTimeout(150)
  assert.equal(Number(await progress.inputValue()), paused)
  await progress.fill('50')
  assert.match(await progress.getAttribute('aria-valuetext'), /connect/)
  await page.getByText('Spatial controls', { exact: false }).click()
  await page.getByRole('slider', { name: 'Rotate the evidence', exact: true }).fill('24')
  await page.getByRole('button', { name: 'Use flat view', exact: true }).click()
  assert.equal(await page.getByRole('slider', { name: 'Rotate the evidence', exact: true }).isDisabled(), true)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Next story stage', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Next story stage', exact: true }).count(), 1)
  await page.getByRole('button', { name: 'Next story stage', exact: true }).click()
  assert.equal(Number(await progress.inputValue()), 0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.getByRole('button', { name: 'Play story', exact: true }).waitFor()
  passed.push('play, pause, scrub, spatial rotation, flat view, reduced motion and preference changes')

  await page.setViewportSize({ width: 375, height: 900 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.getByRole('button', { name: 'Menu', exact: true }).click()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('button', { name: 'Menu', exact: true }).evaluate(el => el === document.activeElement), true)
  await page.getByRole('button', { name: 'Add signal', exact: true }).click()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('button', { name: 'Add signal', exact: true }).evaluate(el => el === document.activeElement), true)
  passed.push('mobile navigation and dialog Escape / focus return')

  for (const width of [320, 375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `demo overflow at ${width}`)
  }
  passed.push('demo overflow at five responsive widths')
  return passed
}

export async function verifyComparison(page, base = 'http://localhost:5178/rcs-frontend-site/') {
  const passed = []
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base)
  const range = page.getByRole('slider', { name: 'Amount of refined design shown' })
  await range.focus()
  await page.keyboard.press('Home')
  assert.equal(await range.inputValue(), '0')
  assert.equal(await page.locator('.after-layer').evaluate(el => getComputedStyle(el).clipPath), 'inset(0px 100% 0px 0px)')
  await page.keyboard.press('End')
  assert.equal(await range.inputValue(), '100')
  assert.equal(await page.locator('.after-layer').evaluate(el => getComputedStyle(el).clipPath), 'inset(0px 0% 0px 0px)')
  await page.keyboard.press('ArrowLeft')
  assert.equal(await range.inputValue(), '99')
  await page.getByRole('button', { name: 'Split view', exact: true }).click()
  assert.equal(await range.inputValue(), '50')
  passed.push('slider keyboard, correct clipping endpoints, preset')
  await page.getByLabel('Preview size').selectOption('phone')
  assert.equal(Math.round((await page.locator('.compare-viewport').boundingBox()).width), 390)
  await page.getByRole('button', { name: 'Explore live', exact: false }).click()
  await page.getByRole('button', { name: 'Workspace', exact: true }).click()
  const demo = page.frameLocator('iframe[title="Interactive Threadline demo with RC’s Frontend Skill"]')
  await demo.getByRole('searchbox', { name: 'Search signals' }).fill('unfindable')
  assert.equal(await demo.getByText('No signals on this thread.').count(), 1)
  passed.push('phone preview and functioning embedded workspace')
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  for (const width of [320, 375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `site overflow at ${width}`)
  }
  passed.push('comparison overflow at five responsive widths')
  return passed
}
